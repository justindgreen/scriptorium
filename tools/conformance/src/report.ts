import type { ContentEntry } from '@scriptorium/content-schema'
import type { AlphaManifest, EntryReport, Loaded } from './run.js'

export type Summary = {
  total: number
  full: number
  partial: number
  manual: number
  pending: number
  none: number
  verified: number
  unverified: number
}

export function summarize(reports: EntryReport[]): Summary {
  const s: Summary = {
    total: 0,
    full: 0,
    partial: 0,
    manual: 0,
    pending: 0,
    none: 0,
    verified: 0,
    unverified: 0,
  }
  for (const r of reports) {
    s.total += 1
    s[r.level] += 1
    if (r.level === 'full' || r.level === 'partial') {
      if (r.verified) s.verified += 1
      else s.unverified += 1
    }
  }
  return s
}

/** Entries that belong to the alpha content set (docs/IMPLEMENTATION_PLAN.md M2.4). */
export function alphaEntries(loaded: Loaded, reports: EntryReport[]): EntryReport[] {
  const a = loaded.alpha
  const owners = new Set([...a.classes, ...a.subclasses, ...a.species])
  const explicit = new Set([
    ...a.classes,
    ...a.subclasses,
    ...a.species,
    ...a.backgrounds,
    ...a.feats,
    ...a.items,
    ...a.monsters,
  ])
  const byUid = new Map(loaded.entries.map((e) => [e.uid, e]))
  return reports.filter((r) => {
    if (explicit.has(r.uid)) return true
    const entry = byUid.get(r.uid)
    if (entry?.kind === 'feature') return Boolean(entry.data.owner && owners.has(entry.data.owner))
    return false
  })
}

export type AlphaGate = {
  features: Summary
  classFeatures: Summary
  verifiedShare: number
  fullOrPartialShare: number
  /** The same share without SRD table placeholder rows (tagged `placeholder`). */
  fullOrPartialShareMechanical: number
  placeholders: number
  unverified: EntryReport[]
  manualOffList: EntryReport[]
  pending: EntryReport[]
  violations: EntryReport[]
}

export function alphaGate(loaded: Loaded, reports: EntryReport[]): AlphaGate {
  const alpha = alphaEntries(loaded, reports)
  const byUid = new Map(loaded.entries.map((e) => [e.uid, e]))
  const classOwners = new Set([...loaded.alpha.classes, ...loaded.alpha.subclasses])
  const classFeatures = alpha.filter((r) => {
    const e = byUid.get(r.uid)
    return e?.kind === 'feature' && e.data.owner !== undefined && classOwners.has(e.data.owner)
  })
  const features = summarize(alpha)
  const cf = summarize(classFeatures)
  const mechanical = classFeatures.filter(
    (r) => !(byUid.get(r.uid)?.tags ?? []).includes('placeholder'),
  )
  const mech = summarize(mechanical)
  const allowed = new Set(loaded.allowlist.map((a) => a.uid))
  return {
    features,
    classFeatures: cf,
    verifiedShare:
      features.verified + features.unverified === 0
        ? 1
        : features.verified / (features.verified + features.unverified),
    fullOrPartialShare: cf.total === 0 ? 1 : (cf.full + cf.partial) / cf.total,
    fullOrPartialShareMechanical: mech.total === 0 ? 1 : (mech.full + mech.partial) / mech.total,
    placeholders: cf.total - mech.total,
    unverified: alpha.filter((r) => (r.level === 'full' || r.level === 'partial') && !r.verified),
    manualOffList: alpha.filter((r) => r.level === 'manual' && !allowed.has(r.uid)),
    pending: alpha.filter((r) => r.level === 'pending' || r.level === 'none'),
    violations: alpha.filter((r) => r.violations.length > 0),
  }
}

function pct(n: number): string {
  return `${Math.round(n * 1000) / 10}%`
}

function row(label: string, s: Summary): string {
  return `| ${label} | ${s.total} | ${s.full} | ${s.partial} | ${s.manual} | ${s.pending + s.none} | ${s.verified} | ${s.unverified} |`
}

const HEADER =
  '| Category | Entries | full | partial | manual | pending | verified | unverified |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'

export function renderReport(loaded: Loaded, reports: EntryReport[], generatedBy: string): string {
  const gate = alphaGate(loaded, reports)
  const byCategory = new Map<string, EntryReport[]>()
  for (const r of reports) {
    const list = byCategory.get(r.category) ?? []
    list.push(r)
    byCategory.set(r.category, list)
  }
  const names = new Map(loaded.entries.map((e) => [e.uid, e.name]))
  const label = (category: string) =>
    category.includes(':')
      ? `${names.get(category) ?? category.split(':').slice(-1)[0]} (${category.split(':')[1] ?? category})`
      : category

  const lines: string[] = []
  lines.push('# Automation coverage')
  lines.push('')
  lines.push(
    `Generated by \`${generatedBy}\` from the committed SRD 5.1 packages and mechanics overlays. Do not edit by hand; see docs/TEST_STRATEGY.md §3–§4.`,
  )
  lines.push('')
  lines.push(
    'A feature is **verified** only when every behavioural case in its overlay passes through the real engine. Entries whose mechanics are structured data with no effects (weapons, armor, classes, spells, monsters) are verified by the schema and the engine reading that data directly. `pending` means mechanics are not authored yet.',
  )
  lines.push('')
  lines.push('## Alpha gate (M2.4 / Gate A1)')
  lines.push('')
  lines.push(HEADER)
  lines.push(row('Alpha set (features, species, background, feat, items, monsters)', gate.features))
  lines.push(row('Alpha class and subclass features', gate.classFeatures))
  lines.push('')
  lines.push(
    `- Verified share of full/partial alpha entries: **${pct(gate.verifiedShare)}** (gate: 100%)`,
  )
  lines.push(
    `- Alpha class and subclass features full or partial: **${pct(gate.fullOrPartialShare)}** of all ${gate.classFeatures.total} rows; **${pct(gate.fullOrPartialShareMechanical)}** of the ${gate.classFeatures.total - gate.placeholders} rows that are not SRD table placeholders (gate: ≥ 95%; ${gate.fullOrPartialShareMechanical >= 0.95 ? 'met' : 'NOT met, see IMPLEMENTATION_PLAN.md M2.4'})`,
  )
  lines.push(
    `- Manual alpha features without an allow-list reason: **${gate.manualOffList.length}** (gate: 0)`,
  )
  lines.push(`- Declaration violations in the alpha set: **${gate.violations.length}** (gate: 0)`)
  lines.push(`- Alpha entries still pending: **${gate.pending.length}**`)
  lines.push('')
  if (gate.unverified.length > 0) {
    lines.push('### Unverified full/partial alpha entries')
    lines.push('')
    for (const r of gate.unverified) {
      const failures = r.cases.filter((c) => !c.ok).map((c) => `${c.name}: ${c.message}`)
      lines.push(
        `- \`${r.uid}\` (${r.level}) ${r.cases.length === 0 ? 'has no behavioural case' : failures.join('; ')}`,
      )
    }
    lines.push('')
  }
  if (gate.manualOffList.length > 0) {
    lines.push('### Manual alpha features missing from the allow-list')
    lines.push('')
    for (const r of gate.manualOffList) lines.push(`- \`${r.uid}\``)
    lines.push('')
  }
  if (gate.pending.length > 0) {
    lines.push('### Pending alpha entries')
    lines.push('')
    for (const r of gate.pending) lines.push(`- \`${r.uid}\``)
    lines.push('')
  }
  lines.push('## Manual allow-list (alpha)')
  lines.push('')
  lines.push('| Feature | Reason |')
  lines.push('| --- | --- |')
  for (const a of loaded.allowlist) lines.push(`| \`${a.uid}\` | ${a.reason} |`)
  lines.push('')
  lines.push('## All content by category')
  lines.push('')
  lines.push(HEADER)
  const sorted = [...byCategory.entries()].sort(([a], [b]) => a.localeCompare(b))
  for (const [category, list] of sorted) lines.push(row(label(category), summarize(list)))
  lines.push(row('**Total**', summarize(reports)))
  lines.push('')
  const failing = reports.filter((r) => r.cases.some((c) => !c.ok) || r.violations.length > 0)
  if (failing.length > 0) {
    lines.push('## Failing cases and violations (all content)')
    lines.push('')
    for (const r of failing) {
      for (const v of r.violations) lines.push(`- \`${r.uid}\`: ${v}`)
      for (const c of r.cases.filter((c) => !c.ok))
        lines.push(`- \`${r.uid}\` / ${c.name}: ${c.message}`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

export type { ContentEntry, AlphaManifest }
